-- =====================================================================
-- Critique: full PostgreSQL schema + demo data
--
-- Tables and columns db.py relies on: users, items, reviews, bookmarks,
-- review_reactions. Everything else adds features the site will grow into.
--
-- Usage (PostgreSQL 13+; tested target is 18):
--   createdb -U postgres critique
--   psql -U postgres -d critique -v ON_ERROR_STOP=1 -f schema.sql
--
-- Re-running drops and recreates every object below, demo data included.
-- =====================================================================

BEGIN;

DROP VIEW IF EXISTS item_cards, item_stats, review_details CASCADE;
DROP FUNCTION IF EXISTS recommend_items(integer, integer, text) CASCADE;
DROP FUNCTION IF EXISTS similar_items(integer, integer) CASCADE;
DROP FUNCTION IF EXISTS set_updated_at() CASCADE;
DROP TABLE IF EXISTS
    recommendation_dismissals, follows, list_items, lists,
    review_reports, review_comments, review_reactions, reviews,
    bookmarks, credits, people, tracks,
    album_details, book_details, movie_details,
    item_genres, genres, items, users
    CASCADE;

-- Keeps updated_at current on every UPDATE (PostgreSQL has no ON UPDATE clause).
CREATE FUNCTION set_updated_at() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at := now();
    RETURN NEW;
END;
$$;


-- =====================================================================
-- 1. Accounts
-- =====================================================================

CREATE TABLE users (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          text NOT NULL CHECK (length(name) BETWEEN 1 AND 100),
    email         text NOT NULL,
    -- Werkzeug generate_password_hash() output. '!' = account that cannot log in.
    password_hash text NOT NULL,
    role          text NOT NULL DEFAULT 'user' CHECK (role IN ('user', 'moderator', 'admin')),
    bio           text CHECK (length(bio) <= 1000),
    avatar_url    text,
    created_at    timestamptz NOT NULL DEFAULT now()
);

-- Emails are unique regardless of case.
CREATE UNIQUE INDEX users_email_key ON users (lower(email));

-- Who follows whom (feed of reviews from people you follow).
CREATE TABLE follows (
    follower_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    followee_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at  timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (follower_id, followee_id),
    CHECK (follower_id <> followee_id)
);
CREATE INDEX idx_follows_followee ON follows (followee_id);


-- =====================================================================
-- 2. Catalogue
-- A movie, book or album is one row in `items`. Medium-specific facts
-- live in *_details tables that are only allowed for the matching type.
-- =====================================================================

CREATE TABLE items (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type        text NOT NULL CHECK (type IN ('movie', 'book', 'music')),
    title       text NOT NULL CHECK (length(title) BETWEEN 1 AND 300),
    creator     text NOT NULL,          -- headline credit shown on cards: director, author or artist
    year        integer CHECK (year BETWEEN -3000 AND 2100),
    description text,
    cover_url   text,                   -- real cover image; NULL = draw the gradient poster
    color1      text NOT NULL CHECK (color1 ~ '^#[0-9A-Fa-f]{6}$'),
    color2      text NOT NULL CHECK (color2 ~ '^#[0-9A-Fa-f]{6}$'),
    featured    boolean NOT NULL DEFAULT false,
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now(),
    -- Full-text search over title and creator ("dune", "nolan", prefix "opp:*").
    search      tsvector GENERATED ALWAYS AS (
                    setweight(to_tsvector('simple', title), 'A') ||
                    setweight(to_tsvector('simple', creator), 'B')
                ) STORED,
    UNIQUE (id, type)                   -- target for the *_details foreign keys below
);
CREATE INDEX idx_items_type_year ON items (type, year);
CREATE INDEX idx_items_title     ON items (lower(title));
CREATE INDEX idx_items_search    ON items USING gin (search);
-- At most one featured item (the home page hero).
CREATE UNIQUE INDEX items_one_featured ON items (featured) WHERE featured;
CREATE TRIGGER items_updated_at BEFORE UPDATE ON items
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE genres (
    id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE CHECK (length(name) BETWEEN 1 AND 60)
);

-- position 1 is the primary genre (the one shown on cards).
CREATE TABLE item_genres (
    item_id  integer NOT NULL REFERENCES items(id) ON DELETE CASCADE,
    genre_id integer NOT NULL REFERENCES genres(id) ON DELETE CASCADE,
    position smallint NOT NULL DEFAULT 1 CHECK (position >= 1),
    PRIMARY KEY (item_id, genre_id),
    UNIQUE (item_id, position)
);
CREATE INDEX idx_item_genres_genre ON item_genres (genre_id);

CREATE TABLE movie_details (
    item_id         integer PRIMARY KEY,
    type            text NOT NULL DEFAULT 'movie' CHECK (type = 'movie'),
    runtime_minutes integer CHECK (runtime_minutes > 0),
    language        text,
    country         text,
    FOREIGN KEY (item_id, type) REFERENCES items(id, type) ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE book_details (
    item_id   integer PRIMARY KEY,
    type      text NOT NULL DEFAULT 'book' CHECK (type = 'book'),
    isbn      text UNIQUE CHECK (isbn ~ '^(\d{9}[\dX]|\d{13})$'),   -- ISBN-10 or ISBN-13, no dashes
    publisher text,
    pages     integer CHECK (pages > 0),
    language  text,
    FOREIGN KEY (item_id, type) REFERENCES items(id, type) ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE album_details (
    item_id    integer PRIMARY KEY,
    type       text NOT NULL DEFAULT 'music' CHECK (type = 'music'),
    label      text,
    album_type text NOT NULL DEFAULT 'studio'
               CHECK (album_type IN ('studio', 'live', 'compilation', 'ep', 'single', 'soundtrack')),
    FOREIGN KEY (item_id, type) REFERENCES items(id, type) ON DELETE CASCADE ON UPDATE CASCADE
);

-- Tracklist of an album. Tracks are listed, not rated; the album is what gets reviewed.
CREATE TABLE tracks (
    id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id          integer NOT NULL REFERENCES album_details(item_id) ON DELETE CASCADE,
    position         smallint NOT NULL CHECK (position >= 1),
    title            text NOT NULL,
    duration_seconds integer CHECK (duration_seconds > 0),
    UNIQUE (item_id, position)
);

-- Directors, actors, authors, artists...
CREATE TABLE people (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       text NOT NULL CHECK (length(name) BETWEEN 1 AND 200),
    bio        text,
    birth_date date,
    photo_url  text
);
CREATE INDEX idx_people_search ON people USING gin (to_tsvector('simple', name));

-- Full credits of an item. items.creator stays the short headline credit.
CREATE TABLE credits (
    item_id        integer NOT NULL REFERENCES items(id) ON DELETE CASCADE,
    person_id      integer NOT NULL REFERENCES people(id) ON DELETE CASCADE,
    role           text NOT NULL CHECK (role IN (
                       'director', 'writer', 'actor', 'producer', 'composer', 'cinematographer',
                       'author', 'translator', 'illustrator',
                       'artist', 'featured_artist', 'songwriter')),
    character_name text,                -- actors only
    position       smallint NOT NULL DEFAULT 1,   -- billing order within the role
    PRIMARY KEY (item_id, person_id, role)
);
CREATE INDEX idx_credits_person ON credits (person_id);


-- =====================================================================
-- 3. Reviews and community
-- Ratings are computed from `reviews`, never stored on items.
-- =====================================================================

-- One rating per user per item; body is optional (rating without a written review).
CREATE TABLE reviews (
    id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    item_id           integer NOT NULL REFERENCES items(id) ON DELETE CASCADE,
    rating            smallint NOT NULL CHECK (rating BETWEEN 1 AND 5),
    body              text CHECK (body IS NULL OR length(btrim(body)) BETWEEN 1 AND 10000),
    contains_spoilers boolean NOT NULL DEFAULT false,
    created_at        timestamptz NOT NULL DEFAULT now(),
    updated_at        timestamptz NOT NULL DEFAULT now(),
    UNIQUE (user_id, item_id)
);
CREATE INDEX idx_reviews_item   ON reviews (item_id, created_at DESC);
CREATE INDEX idx_reviews_latest ON reviews (created_at DESC) WHERE body IS NOT NULL;
CREATE TRIGGER reviews_updated_at BEFORE UPDATE ON reviews
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- Like (1) or dislike (-1) on a review; one per user per review.
CREATE TABLE review_reactions (
    review_id  integer NOT NULL REFERENCES reviews(id) ON DELETE CASCADE,
    user_id    integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    value      smallint NOT NULL CHECK (value IN (1, -1)),
    created_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (review_id, user_id)
);
CREATE INDEX idx_review_reactions_user ON review_reactions (user_id);

-- Replies under a review.
CREATE TABLE review_comments (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_id  integer NOT NULL REFERENCES reviews(id) ON DELETE CASCADE,
    user_id    integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    body       text NOT NULL CHECK (length(btrim(body)) BETWEEN 1 AND 2000),
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_review_comments_review ON review_comments (review_id, created_at);

-- Moderation queue: users flag reviews, moderators/admins resolve them.
CREATE TABLE review_reports (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_id   integer NOT NULL REFERENCES reviews(id) ON DELETE CASCADE,
    reporter_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    reason      text NOT NULL CHECK (reason IN ('spam', 'abuse', 'spoilers', 'off_topic', 'other')),
    note        text CHECK (length(note) <= 1000),
    status      text NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'dismissed', 'actioned')),
    resolved_by integer REFERENCES users(id) ON DELETE SET NULL,
    resolved_at timestamptz,
    created_at  timestamptz NOT NULL DEFAULT now(),
    UNIQUE (review_id, reporter_id),
    CHECK ((status = 'open') = (resolved_at IS NULL))
);
CREATE INDEX idx_review_reports_open ON review_reports (created_at) WHERE status = 'open';


-- =====================================================================
-- 4. Personal collections
-- =====================================================================

-- Items a user saved to come back to (watchlist / to-read / to-listen).
-- The site's bookmark toggle only needs (user_id, item_id); status is optional progress.
CREATE TABLE bookmarks (
    user_id    integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    item_id    integer NOT NULL REFERENCES items(id) ON DELETE CASCADE,
    status     text NOT NULL DEFAULT 'planned' CHECK (status IN ('planned', 'in_progress', 'finished')),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, item_id)
);
CREATE INDEX idx_bookmarks_user_recent ON bookmarks (user_id, created_at DESC);
CREATE TRIGGER bookmarks_updated_at BEFORE UPDATE ON bookmarks
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- User-made lists ("Favourites", "Best of 2023", ...), optionally public.
CREATE TABLE lists (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name        text NOT NULL CHECK (length(name) BETWEEN 1 AND 100),
    description text CHECK (length(description) <= 2000),
    is_public   boolean NOT NULL DEFAULT true,
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now(),
    UNIQUE (user_id, name)
);
CREATE TRIGGER lists_updated_at BEFORE UPDATE ON lists
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE list_items (
    list_id  integer NOT NULL REFERENCES lists(id) ON DELETE CASCADE,
    item_id  integer NOT NULL REFERENCES items(id) ON DELETE CASCADE,
    position integer NOT NULL CHECK (position >= 1),
    note     text CHECK (length(note) <= 500),
    added_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (list_id, item_id)
);
CREATE INDEX idx_list_items_order ON list_items (list_id, position);
CREATE INDEX idx_list_items_item  ON list_items (item_id);

-- "Not interested": hides an item from that user's recommendations.
CREATE TABLE recommendation_dismissals (
    user_id    integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    item_id    integer NOT NULL REFERENCES items(id) ON DELETE CASCADE,
    created_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, item_id)
);


-- =====================================================================
-- 5. Views: what db.py selects from
-- =====================================================================

-- Rating numbers per item. rating is NULL until the first review.
CREATE VIEW item_stats AS
SELECT i.id AS item_id,
       ROUND(AVG(r.rating), 1)::float8          AS rating,
       COUNT(r.id)                              AS rating_count,
       COUNT(r.id) FILTER (WHERE r.body IS NOT NULL) AS review_count
FROM items i
LEFT JOIN reviews r ON r.item_id = i.id
GROUP BY i.id;

-- One row per item, shaped like the dicts db.py returns today (the "<item select>"),
-- plus `score`: a Bayesian average (IMDb-style) so one 5-star review can't top the charts.
-- Sort "top rated" by score, show rating.
CREATE VIEW item_cards AS
WITH type_mean AS (
    SELECT i.type, AVG(r.rating) AS mean
    FROM reviews r JOIN items i ON i.id = r.item_id
    GROUP BY i.type
)
SELECT i.id, i.type, i.title, i.creator, i.year, i.description, i.cover_url,
       i.color1, i.color2, i.featured, i.created_at,
       g.genre,
       COALESCE(g.genres, '{}')                 AS genres,
       s.rating, s.rating_count, s.review_count,
       CASE WHEN s.rating_count > 0 THEN
           ROUND(((s.rating_count * s.rating + 10 * m.mean) / (s.rating_count + 10))::numeric, 3)::float8
       END                                      AS score      -- NULL until rated
FROM items i
JOIN item_stats s ON s.item_id = i.id
LEFT JOIN type_mean m ON m.type = i.type
LEFT JOIN LATERAL (
    SELECT (array_agg(gn.name ORDER BY ig.position))[1]  AS genre,
           array_agg(gn.name ORDER BY ig.position)       AS genres
    FROM item_genres ig JOIN genres gn ON gn.id = ig.genre_id
    WHERE ig.item_id = i.id
) g ON true;

-- Reviews with author name and reaction/comment counts. The viewer's own reaction
-- (my_reaction) depends on who is logged in, so db.py adds it in its query.
CREATE VIEW review_details AS
SELECT r.id, r.user_id, r.item_id, r.rating, r.body, r.contains_spoilers,
       r.created_at, r.updated_at,
       u.name,
       i.title, i.type,
       (SELECT COUNT(*) FROM review_reactions x WHERE x.review_id = r.id AND x.value = 1)  AS likes,
       (SELECT COUNT(*) FROM review_reactions x WHERE x.review_id = r.id AND x.value = -1) AS dislikes,
       (SELECT COUNT(*) FROM review_comments  c WHERE c.review_id = r.id)                 AS comment_count
FROM reviews r
JOIN users u ON u.id = r.user_id
JOIN items i ON i.id = r.item_id;


-- =====================================================================
-- 6. Recommendations
-- =====================================================================

-- Personal picks for a user, optionally for one section (p_type = 'movie' | 'book' | 'music').
-- Mixes three signals, strongest first:
--   1. people who liked (4-5 stars) what you liked also liked X        (collaborative)
--   2. X shares genres with what you liked                              (content)
--   3. X is well rated overall                                          (cold start)
-- Skips anything the user already rated, bookmarked or dismissed.
CREATE FUNCTION recommend_items(p_user_id integer, p_limit integer DEFAULT 10, p_type text DEFAULT NULL)
RETURNS TABLE (item_id integer, score numeric)
LANGUAGE sql STABLE AS $$
    WITH liked AS (
        SELECT r.item_id FROM reviews r
        WHERE r.user_id = p_user_id AND r.rating >= 4
    ),
    neighbours AS (
        SELECT r.user_id, COUNT(*) AS overlap
        FROM reviews r JOIN liked l ON l.item_id = r.item_id
        WHERE r.user_id <> p_user_id AND r.rating >= 4
        GROUP BY r.user_id
    ),
    liked_genres AS (
        SELECT ig.genre_id, COUNT(*) AS weight
        FROM item_genres ig JOIN liked l ON l.item_id = ig.item_id
        GROUP BY ig.genre_id
    ),
    signals AS (
        SELECT r.item_id, (n.overlap * (r.rating - 3))::numeric AS score
        FROM reviews r JOIN neighbours n ON n.user_id = r.user_id
        WHERE r.rating >= 4
      UNION ALL
        SELECT ig.item_id, (lg.weight * 0.5)::numeric
        FROM item_genres ig JOIN liked_genres lg ON lg.genre_id = ig.genre_id
      UNION ALL
        SELECT c.id, (COALESCE(c.score, 0) * 0.1)::numeric
        FROM item_cards c
    )
    SELECT s.item_id, ROUND(SUM(s.score), 3) AS score
    FROM signals s
    JOIN items i ON i.id = s.item_id
    WHERE (p_type IS NULL OR i.type = p_type)
      AND NOT EXISTS (SELECT 1 FROM reviews r   WHERE r.user_id = p_user_id AND r.item_id = s.item_id)
      AND NOT EXISTS (SELECT 1 FROM bookmarks b WHERE b.user_id = p_user_id AND b.item_id = s.item_id)
      AND NOT EXISTS (SELECT 1 FROM recommendation_dismissals d
                      WHERE d.user_id = p_user_id AND d.item_id = s.item_id)
    GROUP BY s.item_id
    ORDER BY score DESC, s.item_id
    LIMIT p_limit;
$$;

-- "More like this" on an item page: shared genres, shared people (same director,
-- author, artist, actor) and being liked by the same users. Same type ranks higher.
CREATE FUNCTION similar_items(p_item_id integer, p_limit integer DEFAULT 6)
RETURNS TABLE (item_id integer, score numeric)
LANGUAGE sql STABLE AS $$
    WITH signals AS (
        SELECT b.item_id, 1.0 AS score
        FROM item_genres a JOIN item_genres b ON b.genre_id = a.genre_id
        WHERE a.item_id = p_item_id
      UNION ALL
        SELECT DISTINCT b.item_id, 2.0
        FROM credits a JOIN credits b ON b.person_id = a.person_id
        WHERE a.item_id = p_item_id
      UNION ALL
        SELECT b.item_id, 0.5
        FROM reviews a JOIN reviews b ON b.user_id = a.user_id
        WHERE a.item_id = p_item_id AND a.rating >= 4 AND b.rating >= 4
    )
    SELECT s.item_id,
           ROUND(SUM(s.score) * CASE WHEN i.type = me.type THEN 1.5 ELSE 1 END, 3) AS score
    FROM signals s
    JOIN items i  ON i.id = s.item_id
    JOIN items me ON me.id = p_item_id
    WHERE s.item_id <> p_item_id
    GROUP BY s.item_id, i.type, me.type
    ORDER BY score DESC, s.item_id
    LIMIT p_limit;
$$;


